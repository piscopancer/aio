const BINDINGS: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/bindings.ts");

fn export_bindings(builder: &Builder<tauri::Wry>) {
  builder
    .export(
      specta_typescript::Typescript::default()
        .header("// @ts-nocheck\n// Generated by tauri-specta from src-tauri, do not edit.\n"),
      BINDINGS,
    )
    .expect("failed to export typescript bindings");
  let source = fs::read_to_string(BINDINGS).expect("failed to read exported bindings");
  fs::write(BINDINGS, two_space_indent(&source)).expect("failed to reindent exported bindings");
}

/// The exporter indents with tabs and 4 spaces; the project uses 2 spaces per level.
fn two_space_indent(source: &str) -> String {
  source
    .lines()
    .map(|line| {
      let body = line.trim_start_matches(['\t', ' ']);
      let indent = &line[..line.len() - body.len()];
      let levels = indent.chars().map(|c| if c == '\t' { 4 } else { 1 }).sum::<usize>() / 4;
      format!("{}{body}\n", "  ".repeat(levels))
    })
    .collect()
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
  let scenario = Cli::parse().scenario();
  let builder = specta_builder();

  #[cfg(debug_assertions)]
  export_bindings(&builder);

  tauri::Builder::default()
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_clipboard_manager::init())
    .plugin(tauri_plugin_decorum::init())
    .plugin(tauri_plugin_process::init())
    .plugin(tauri_plugin_opener::init())
    .plugin(tauri_plugin_updater::Builder::new().build())
    .invoke_handler(builder.invoke_handler())
    .setup(move |app| {
      builder.mount_events(app);
      // the toolbar stands in for the title bar; on Windows decorum draws the window buttons into it, keeping snap layouts
      if let Some(window) = app.get_webview_window("main") {
        window.create_overlay_titlebar()?;
        #[cfg(windows)]
        disable_browser_keys(&window);
      }
      let data_dir = app.path().app_data_dir()?;
      fs::create_dir_all(&data_dir)?;
      let store = Arc::new(match scenario {
        Some(_) => SqliteStore::in_memory()?,
        None => SqliteStore::open(&data_dir.join("aio.db"))?,
      });
      let notifier = Arc::new(TauriNotifier(app.handle().clone()));
      let covers_dir = data_dir.join("covers");
      let files = Arc::new(LocalAudioFiles::new(covers_dir.clone()));
      let library = Arc::new(LibraryService::new(
        store.clone(),
        store.clone(),
        files.clone(),
        notifier.clone(),
      ));
      let playlists = Arc::new(PlaylistService::new(store.clone()));
      let pins = Arc::new(PinService::new(store.clone()));
      let cover_store = Arc::new(CoverStore::new(covers_dir));
      let covers = Arc::new(CoverService::new(cover_store.clone()));
      let tools = Arc::new(ToolKit::new(data_dir.join("tools")));
      let music_dir = app.path().audio_dir().unwrap_or_else(|_| data_dir.join("downloads"));
      let downloads = Arc::new(DownloadService::new(
        Arc::new(YtDlpMedia::new(tools.clone())),
        tools,
        store.clone(),
        library.clone(),
        playlists.clone(),
        notifier.clone(),
        music_dir,
      ));

      let (player, inbox) = player_channel(store.playback_settings());
      let player = Arc::new(player);
      #[cfg(windows)]
      if let Some(window) = app.get_webview_window("main") {
        interface::taskbar::attach(&window, player.clone());
        interface::media_session::attach(&window, player.clone());
      }
      let (settings, player_queries, player_notifier) = (store.clone(), store.clone(), notifier.clone());
      audio::spawn(move |output| PlaybackService::new(output, inbox, settings, player_queries, player_notifier).run());
      let lyrics = Arc::new(LyricsService::new(
        files.clone(),
        Arc::new(Lrclib::new()),
        store.clone(),
        store.clone(),
        player.clone(),
      ));
      // finds of the last session that could not be written while their song played
      lyrics.write_unwritten_later();
      let tag_search = Arc::new(TagSearchService::new(
        vec![
          Arc::new(AcoustId::new()),
          Arc::new(MusicBrainz::new()),
          Arc::new(Itunes::russia()),
          Arc::new(Itunes::united_states()),
          Arc::new(Deezer::new()),
          Arc::new(Bandcamp::new()),
          Arc::new(YoutubeMusic::new()),
        ],
        store.clone(),
        Arc::new(CoverDownloads::new()),
        cover_store,
      ));
      let tags = Arc::new(TagService::new(
        files.clone(),
        files,
        store.clone(),
        store.clone(),
        player.clone(),
        notifier.clone(),
      ));

      if scenario.is_none() {
        // picks up files changed while the app was closed, and re-reads those a migration marked as changed
        let startup = library.clone();
        std::thread::spawn(move || {
          if let Err(error) = startup.scan() {
            eprintln!("startup scan failed: {error}");
          }
        });
      }
      if let Some(scenario) = scenario {
        scenario::seed(scenario, store.as_ref(), store.as_ref(), &playlists, store.as_ref())?;
        scenario::start(scenario, &player, store.as_ref())?;
      }
      app.manage(AppState {
        library,
        playlists,
        pins,
        covers,
        tags,
        tag_search,
        lyrics,
        downloads,
        queries: store,
        player,
        scenario,
      });
      Ok(())
    })
    .run(tauri::generate_context!())
    .expect("error while running tauri application");
}

/// Turns off the webview's browser shortcuts, such as Ctrl+F opening a find bar over the app's own search, Ctrl+P
/// printing and F5 reloading; the developer tools stay reachable through Shift and right-click in dev builds.
#[cfg(windows)]
fn disable_browser_keys(window: &tauri::WebviewWindow) {
  use webview2_com::Microsoft::Web::WebView2::Win32::ICoreWebView2Settings3;
  use windows_core::Interface;

  let result = window.with_webview(|webview| {
    // SAFETY: the controller belongs to this live webview and is used on its own thread inside the callback
    let disabled = unsafe {
      webview
        .controller()
        .CoreWebView2()
        .and_then(|core| core.Settings())
        .and_then(|settings| settings.cast::<ICoreWebView2Settings3>())
        .and_then(|settings| settings.SetAreBrowserAcceleratorKeysEnabled(false))
    };
    if let Err(error) = disabled {
      eprintln!("browser shortcuts stay on: {error}");
    }
  });
  if let Err(error) = result {
    eprintln!("browser shortcuts stay on: {error}");
  }
}

